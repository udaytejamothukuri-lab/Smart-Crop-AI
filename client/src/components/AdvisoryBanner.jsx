import React from 'react';
import { AlertTriangle, Info } from 'lucide-react';

export default function AdvisoryBanner({ text, variant = 'warning' }) {
  const defaultText = "Agricultural Advisory Notice: Recommendations generated by SmartCrop AI are deterministic heuristic estimates based on published agro-ecological guidelines. They do not substitute for certified soil laboratory assays, local agricultural extension officer consultation, or seasonal micro-climate forecasts.";

  const isWarning = variant === 'warning';

  return (
    <div className={`p-4 rounded-xl border flex items-start gap-3 my-4 ${
      isWarning 
        ? 'bg-amber-50/80 border-amber-200 text-amber-900' 
        : 'bg-agri-50 border-agri-200 text-agri-950'
    }`}>
      {isWarning ? (
        <AlertTriangle className="w-5 h-5 text-amber-600 flex-shrink-0 mt-0.5" />
      ) : (
        <Info className="w-5 h-5 text-agri-700 flex-shrink-0 mt-0.5" />
      )}
      <div className="text-xs sm:text-sm leading-relaxed">
        <strong className="font-semibold block mb-0.5">Advisory Notice:</strong>
        {text || defaultText}
      </div>
    </div>
  );
}
